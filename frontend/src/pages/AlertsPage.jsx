import { useCallback, useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { alertApi } from "../api/alertApi";
import { formatDateTime, formatEnumLabel } from "../utils/formatters";

function AlertsPage() {
  const [alerts, setAlerts] = useState([]);
  const [isLoading, setIsLoading] = useState(true);
  const [errorMessage, setErrorMessage] = useState("");

  const loadOpenAlerts = useCallback(async () => {
    try {
      setIsLoading(true);
      setErrorMessage("");

      const data = await alertApi.getOpenAlerts();
      setAlerts(data);
    } catch {
      setErrorMessage("Failed to load alerts.");
    } finally {
      setIsLoading(false);
    }
  }, []);

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect
    loadOpenAlerts();
  }, [loadOpenAlerts]);

  const handleAcknowledge = async (alertId) => {
    try {
      setErrorMessage("");
      await alertApi.acknowledge(alertId);
      await loadOpenAlerts();
    } catch {
      setErrorMessage("Failed to acknowledge alert.");
    }
  };

  const handleResolve = async (alertId) => {
    try {
      setErrorMessage("");
      await alertApi.resolve(alertId);
      await loadOpenAlerts();
    } catch {
      setErrorMessage("Failed to resolve alert.");
    }
  };

  if (isLoading && alerts.length === 0) {
    return <p>Loading alerts...</p>;
  }

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <h2>Open Alerts</h2>
          <p>Review active logistics risk alerts generated by monitoring rules.</p>
        </div>

        <button type="button" disabled={isLoading} onClick={loadOpenAlerts}>
          {isLoading ? "Refreshing..." : "Refresh"}
        </button>
      </div>

      {errorMessage && <p className="error-message">{errorMessage}</p>}

      <div className="panel">
        {alerts.length === 0 ? (
          <p>No open alerts.</p>
        ) : (
          alerts.map((alert) => (
            <div
              key={alert.id}
              className={`alert-item ${alert.alertType?.toLowerCase()}`}
            >
              <div>
                <strong>{alert.title}</strong>
                <p>{alert.message}</p>
                <div className="alert-meta">
                  <span>
                    Shipment:{" "}
                    <Link to={`/shipments/${alert.shipmentId}`}>
                      {alert.shipmentCode}
                    </Link>
                  </span>
                  <span>Type: {formatEnumLabel(alert.alertType)}</span>
                  <span>Created: {formatDateTime(alert.createdAt)}</span>
                </div>
              </div>

              <div className="alert-actions">
                <span className={`severity ${alert.severity?.toLowerCase()}`}>
                  {formatEnumLabel(alert.severity)}
                </span>

                <button
                  type="button"
                  disabled={isLoading}
                  onClick={() => handleAcknowledge(alert.id)}
                >
                  Acknowledge
                </button>

                <button
                  type="button"
                  className="secondary-button"
                  disabled={isLoading}
                  onClick={() => handleResolve(alert.id)}
                >
                  Resolve
                </button>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
}

export default AlertsPage;
