-- Smart Automotive Logistics System - Supabase PostgreSQL schema
-- Paste this into Supabase Dashboard > SQL Editor > New query.
-- This script is safe to rerun on an empty or already-created schema.

create table if not exists app_users (
    id bigint generated by default as identity primary key,
    full_name varchar(255) not null,
    email varchar(255) not null,
    password_hash varchar(255) not null,
    role varchar(255) not null,
    active boolean not null default true,
    company_name varchar(255),
    operating_location varchar(255),
    location_latitude double precision,
    location_longitude double precision,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    constraint uk_app_user_email unique (email),
    constraint ck_app_users_role check (
        role in ('ADMIN', 'MANUFACTURER', 'LOGISTICS_PROVIDER', 'DEALERSHIP')
    )
);

create table if not exists vehicle_models (
    id bigint generated by default as identity primary key,
    model_code varchar(80) not null,
    brand varchar(255) not null,
    display_name varchar(255) not null,
    active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    constraint uk_vehicle_models_model_code unique (model_code)
);

create table if not exists shipment_party_profiles (
    id bigint generated by default as identity primary key,
    party_key varchar(120) not null,
    party_role varchar(255) not null,
    company_name varchar(255) not null,
    operating_location varchar(255) not null,
    location_latitude double precision not null,
    location_longitude double precision not null,
    active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    constraint uk_shipment_party_profiles_party_key unique (party_key),
    constraint ck_shipment_party_profiles_party_role check (
        party_role in ('MANUFACTURER', 'DEALERSHIP')
    )
);

create table if not exists shipments (
    id bigint generated by default as identity primary key,
    shipment_code varchar(255),
    vehicle_vin varchar(255),
    vehicle_model_code varchar(80),
    vehicle_model varchar(255),
    manufacturer_key varchar(120),
    dealership_key varchar(120),
    origin varchar(255),
    destination varchar(255),
    origin_latitude double precision,
    origin_longitude double precision,
    destination_latitude double precision,
    destination_longitude double precision,
    dealership_name varchar(255),
    status varchar(255),
    estimated_arrival timestamp(6) without time zone,
    estimated_departure timestamp(6) without time zone,
    current_stage varchar(255),
    stock_location varchar(255),
    work_in_progress_status varchar(255),
    responsible_person varchar(255),
    responsible_contact varchar(255),
    customer_name varchar(255),
    customer_contact varchar(255),
    customer_address varchar(500),
    shipment_document_reference varchar(255),
    receipt_confirmed_at timestamp(6) without time zone,
    receipt_confirmed_by varchar(255),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    constraint ck_shipments_status check (
        status is null or status in (
            'CREATED',
            'READY_FOR_DISPATCH',
            'PICKED_UP',
            'IN_TRANSIT',
            'DELAYED',
            'ARRIVED',
            'DELIVERED',
            'CANCELLED'
        )
    ),
    constraint ck_shipments_current_stage check (
        current_stage is null or current_stage in (
            'MANUFACTURING',
            'STOCK_YARD',
            'WORK_IN_PROGRESS',
            'READY_FOR_DISPATCH',
            'IN_TRANSIT',
            'ARRIVED_AT_DEALERSHIP',
            'DELIVERED'
        )
    ),
    constraint ck_shipments_wip_status check (
        work_in_progress_status is null or work_in_progress_status in (
            'NOT_APPLICABLE',
            'NOT_STARTED',
            'IN_PROGRESS',
            'ON_HOLD',
            'COMPLETED'
        )
    )
);

create table if not exists tracking_events (
    id bigint generated by default as identity primary key,
    latitude double precision,
    longitude double precision,
    speed double precision,
    condition_status varchar(255),
    recorded_at timestamp(6) without time zone,
    shipment_id bigint not null,
    constraint fk_tracking_events_shipment
        foreign key (shipment_id) references shipments (id),
    constraint ck_tracking_events_condition_status check (
        condition_status is null or condition_status in (
            'NORMAL',
            'IDLE',
            'DELAYED',
            'ROUTE_DEVIATION',
            'SENSOR_WARNING'
        )
    )
);

create table if not exists shipment_events (
    id bigint generated by default as identity primary key,
    event_type varchar(255) not null,
    description varchar(1000) not null,
    previous_status varchar(255),
    new_status varchar(255),
    created_at timestamp(6) without time zone,
    shipment_id bigint not null,
    constraint fk_shipment_events_shipment
        foreign key (shipment_id) references shipments (id),
    constraint ck_shipment_events_event_type check (
        event_type in (
            'SHIPMENT_CREATED',
            'STATUS_CHANGED',
            'TRACKING_UPDATED',
            'DELAY_DETECTED',
            'IDLE_DETECTED',
            'ALERT_CREATED',
            'DELIVERY_CONFIRMED'
        )
    )
);

create table if not exists alerts (
    id bigint generated by default as identity primary key,
    alert_type varchar(255) not null,
    severity varchar(255) not null,
    status varchar(255) not null,
    title varchar(255) not null,
    message varchar(1000) not null,
    created_at timestamp(6) without time zone,
    acknowledged_at timestamp(6) without time zone,
    resolved_at timestamp(6) without time zone,
    shipment_id bigint not null,
    constraint fk_alerts_shipment
        foreign key (shipment_id) references shipments (id),
    constraint ck_alerts_type check (
        alert_type in (
            'DELAY',
            'IDLE',
            'ETA_OVERDUE',
            'ROUTE_DEVIATION',
            'PROGRESS_SHORTFALL',
            'SENSOR_WARNING',
            'MISSING_UPDATE'
        )
    ),
    constraint ck_alerts_severity check (
        severity in ('LOW', 'MEDIUM', 'HIGH')
    ),
    constraint ck_alerts_status check (
        status in ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')
    )
);

create table if not exists blockchain_records (
    id bigint generated by default as identity primary key,
    shipment_id bigint not null,
    shipment_event_id bigint not null,
    event_hash varchar(1000) not null,
    transaction_hash varchar(255),
    block_number bigint,
    status varchar(255) not null,
    recorded_at timestamp(6) without time zone,
    verified_at timestamp(6) without time zone,
    verification_message varchar(1000),
    constraint uk_blockchain_records_shipment_event unique (shipment_event_id),
    constraint ck_blockchain_records_status check (
        status in ('PENDING', 'RECORDED', 'FAILED')
    )
);

create table if not exists admin_notifications (
    id bigint generated by default as identity primary key,
    type varchar(255) not null,
    status varchar(255) not null,
    title varchar(255) not null,
    message varchar(1500) not null,
    reference_type varchar(255),
    reference_id bigint,
    created_at timestamp(6) without time zone,
    read_at timestamp(6) without time zone,
    constraint ck_admin_notifications_type check (
        type in ('BLOCKCHAIN_TAMPER_DETECTED', 'SYSTEM_ALERT')
    ),
    constraint ck_admin_notifications_status check (
        status in ('UNREAD', 'READ')
    )
);

create table if not exists company_notifications (
    id bigint generated by default as identity primary key,
    type varchar(255) not null,
    status varchar(255) not null,
    recipient_company varchar(255) not null,
    title varchar(255) not null,
    message varchar(1500) not null,
    reference_type varchar(255),
    reference_id bigint,
    sent_at timestamp(6) without time zone,
    constraint ck_company_notifications_type check (
        type in ('BLOCKCHAIN_TAMPER_ALERT', 'SHIPMENT_INTEGRITY_ALERT')
    ),
    constraint ck_company_notifications_status check (
        status in ('SENT', 'FAILED')
    )
);

create table if not exists integrity_cases (
    id bigint generated by default as identity primary key,
    blockchain_record_id bigint,
    shipment_id bigint,
    shipment_event_id bigint,
    status varchar(255) not null,
    resolution_type varchar(255),
    title varchar(255) not null,
    description varchar(1500) not null,
    investigation_notes varchar(2000),
    resolution_notes varchar(2000),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    resolved_at timestamp(6) without time zone,
    constraint ck_integrity_cases_status check (
        status in (
            'OPEN',
            'UNDER_INVESTIGATION',
            'COMPANY_NOTIFIED',
            'RESOLVED',
            'ESCALATED'
        )
    ),
    constraint ck_integrity_cases_resolution_type check (
        resolution_type is null or resolution_type in (
            'FALSE_POSITIVE',
            'LEGACY_TEST_RECORD',
            'DATA_CORRECTION_REQUIRED',
            'CONFIRMED_TAMPERING',
            'SYSTEM_ERROR',
            'OTHER'
        )
    )
);

alter table app_users
    add column if not exists company_name varchar(255),
    add column if not exists operating_location varchar(255),
    add column if not exists location_latitude double precision,
    add column if not exists location_longitude double precision;

alter table shipments
    add column if not exists vehicle_model_code varchar(80),
    add column if not exists manufacturer_key varchar(120),
    add column if not exists dealership_key varchar(120);

create index if not exists idx_app_users_email on app_users (email);
create index if not exists idx_app_users_role_active_company
    on app_users (role, active, company_name);
create index if not exists idx_vehicle_models_active_sort
    on vehicle_models (active, sort_order, display_name);
create index if not exists idx_shipment_party_profiles_role_active_sort
    on shipment_party_profiles (party_role, active, sort_order, company_name);
create index if not exists idx_shipments_status on shipments (status);
create index if not exists idx_shipments_current_stage on shipments (current_stage);
create index if not exists idx_shipments_created_at on shipments (created_at desc);
create index if not exists idx_shipments_shipment_code on shipments (shipment_code);
create index if not exists idx_shipments_vehicle_model_code
    on shipments (vehicle_model_code);
create index if not exists idx_shipments_manufacturer_key
    on shipments (manufacturer_key);
create index if not exists idx_shipments_dealership_key
    on shipments (dealership_key);
create unique index if not exists uk_shipments_shipment_code
    on shipments (shipment_code)
    where shipment_code is not null;
create index if not exists idx_tracking_events_shipment_recorded_at
    on tracking_events (shipment_id, recorded_at desc);
create index if not exists idx_shipment_events_shipment_created_at
    on shipment_events (shipment_id, created_at desc);
create index if not exists idx_alerts_status_created_at
    on alerts (status, created_at desc);
create index if not exists idx_alerts_shipment_created_at
    on alerts (shipment_id, created_at desc);
create unique index if not exists uk_alerts_open_shipment_type
    on alerts (shipment_id, alert_type)
    where status = 'OPEN';
create index if not exists idx_blockchain_records_recorded_at
    on blockchain_records (recorded_at desc);
create index if not exists idx_blockchain_records_shipment_id
    on blockchain_records (shipment_id);
create index if not exists idx_admin_notifications_status_created_at
    on admin_notifications (status, created_at desc);
create index if not exists idx_company_notifications_sent_at
    on company_notifications (sent_at desc);
create index if not exists idx_integrity_cases_status_created_at
    on integrity_cases (status, created_at desc);

